test('owner judgment persists, exports SHA-bound votes without approving production',async({page})=>{
 await page.goto('./tools/asset-gallery.html');
 await expect(page.locator('.asset')).toHaveCount(194);
 const box=page.locator('article[data-id="FOX-05"]');
 await box.locator('button[data-vote="keep"]').click();
 await expect(box.locator('button[data-vote="keep"]')).toHaveAttribute('aria-pressed','true');
 await box.locator('textarea').fill('Great red warning shape. Keep the purple scarf.');
 await page.reload();await expect(page.locator('.asset')).toHaveCount(194);
 await expect(page.locator('article[data-id="FOX-05"] button[data-vote="keep"]')).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('#voted')).toHaveText('1');
 const started=page.waitForEvent('download');
 await page.locator('#export-votes').click();
 const download=await started,content=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
 expect(content.schemaVersion).toBe(1);expect(content.recordCount).toBe(1);
 expect(content.votes[0]).toMatchObject({id:'FOX-05',decision:'keep',notes:'Great red warning shape. Keep the purple scarf.'});
 expect(content.votes[0].sha256).toMatch(/^[0-9a-f]{64}$/);
 await page.goto('./?art=classic');
 expect((await page.evaluate(()=>window.__SHAKEDOWN_QA?.assets?.())).productionLoaded).toBe(0);
});
test('tampered image is SHA-rejected and does not block the game or invent art approval',async({page})=>{
 test.setTimeout(50000);
 await page.route('**/assets/production/birthday/bd_01.png',route=>route.fulfill({contentType:'image/png',body:'not the original hash'}));
 await page.goto('./?art=curated');
 await expect.poll(async()=>page.evaluate(()=>window.__SHAKEDOWN_QA?.assets?.().curatedSelected),{timeout:23000}).toBe(28);
 const art=await page.evaluate(()=>window.__SHAKEDOWN_QA.assets());
 expect(art.curatedLoaded).toBe(27);
 expect(art.curatedErrors.join(' ')).toContain('BD-01');
 expect(art.productionLoaded).toBe(0);
 await page.locator('#start-btn').click();
 expect((await page.evaluate(()=>window.__SHAKEDOWN_QA.snapshot())).mode).toBe('playing');
});
